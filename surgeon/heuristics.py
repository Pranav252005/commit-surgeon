def classify_kind(path: str, hunk_text: str = "") -> str:
    p = path.lower()
    name = posixpath.basename(p)
    ext = posixpath.splitext(name)[1]
    parts = set(p.split("/")[:-1])
    if name in LOCKFILES:
        return "lockfile"
    if parts & GENERATED_PARTS or name.endswith(GENERATED_SUFFIXES) or any(m in hunk_text[:600].lower() for m in GENERATED_MARKERS):
        return "generated"
    if is_test_path(p):
        return "test"
    stem = posixpath.splitext(name)[0]
    if ext in DOC_EXTS or "docs" in parts or "doc" in parts or stem in DOC_NAMES:
        return "docs"
    if ext in CONFIG_EXTS or name in {"dockerfile", "makefile"} or p.startswith(".github/"):
        return "config"
    return "code"


def _squash(lines: list[str]) -> str:
    return re.sub(r"\s+", "", "".join(lines))


def is_whitespace_only(h: Hunk) -> bool:
    if h.pseudo or not (h.added_lines or h.removed_lines):
        return False
    return _squash(h.added_lines) == _squash(h.removed_lines)


def issue_terms(title: str, body: str) -> dict[str, set[str]]:
    """Paths and identifiers the issue talks about. `paths` are strong evidence, `words` are weak."""
    text = f"{title}\n{body}"
    paths = {m.strip("`'\"") for m in re.findall(r"[\w./-]+\.(?:py|js|jsx|ts|tsx|go|rs|java|rb|c|h|cpp|md|rst|toml|ya?ml|json)\b", text)}
    ticks = set(re.findall(r"`([^`\n]{2,60})`", text))
    idents = {w for t in ticks for w in _WORD.findall(t)}
    words = {w.lower() for w in _WORD.findall(title)} - _STOP
    return {"paths": paths, "idents": idents, "words": words}


@dataclass
class IssueArea:
    terms: dict[str, set[str]]
    has_issue: bool

    def mentions(self, path: str, symbol_names: set[str]) -> list[str]:
        hits: list[str] = []
        base = posixpath.basename(path)
        stem = posixpath.splitext(base)[0].lower()
        for p in self.terms["paths"]:
            if path.endswith(p) or posixpath.basename(p) == base:
                hits.append(f"text names file {p}")
        ids = self.terms["idents"]
        for s in symbol_names:
            if s in ids or s.split(".")[-1] in ids:
                hits.append(f"text names symbol `{s}`")
        if stem in {w.lower() for w in ids} and len(stem) > 2:
            hits.append(f"text names module `{stem}`")
        words = self.terms["words"]
        path_words = {w.lower() for w in _WORD.findall(path)} | {w.lower() for s in symbol_names for w in re.findall(r"[A-Za-z]{3,}", s)}
        shared = sorted(words & path_words)
        if shared and not hits:
            hits.append("title shares words with the path/symbol: " + ", ".join(shared[:3]))
        return hits


def apply(files: list[FileChange], graph: ImportGraph | None, issue_title: str = "", issue_body: str = "", source: str = "issue") -> None:
    """source: "issue" when the text is the linked issue, "pr" when there is no issue and the PR text stands in."""
    area = IssueArea(issue_terms(issue_title, issue_body), bool(issue_title))
    hit_tag, miss_tag = f"mentioned_by_{source}", f"not_mentioned_by_{source}"
    for fc in files:
        file_hits = area.mentions(fc.path, set()) if area.has_issue else []
        for h in fc.hunks:
            h.kind = classify_kind(fc.path, h.text)
            h.tags = [h.kind]
            if h.pseudo and fc.status == "renamed" and not fc.binary:
                h.tags.append("rename_only")
                h.label, h.reason = "cleanup", f"pure rename {fc.old_path} -> {fc.path}, no content change"
                continue
            if h.pseudo:
                h.tags.append("metadata_only")
                continue
            if is_whitespace_only(h):
                h.tags.append("whitespace_only")
                h.label, h.reason = "cleanup", "only whitespace changed"
                continue
            if h.kind in {"lockfile", "generated"}:
                h.label, h.reason = "ancillary", f"{h.kind} file, follows whichever change produced it"
                continue
            hits = area.mentions(fc.path, {h.symbol} if h.symbol else set()) if area.has_issue else []
            hits = hits or file_hits
            if hits:
                h.tags.append(hit_tag)
                h.reason = "; ".join(hits[:2])
            elif area.has_issue:
                h.tags.append(miss_tag)
